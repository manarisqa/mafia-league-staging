export function seasonText(locale: Locale) {
  return locale === "uk" ? uk : ru;
}

export function seasonLabel(period: ClubPeriod, locale: Locale) {
  const text = seasonText(locale);
  if (!period.year) return text.all;
  return period.quarter ? `${period.year} · ${period.quarter} ${text.quarter}` : `${text.year} ${period.year}`;
}
