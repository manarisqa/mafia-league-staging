export function siteText(locale: Locale, text: string) {
  if (locale !== "uk") return text;
  if (Object.hasOwn(ukrainian, text)) return ukrainian[text];
  return refereeText(locale, text)
    .replace(/^Заполнено мест: (\d+) из (\d+)$/, "Заповнено місць: $1 із $2")
    .replace(/^Место (\d+): проверьте игрока, роль и фолы\.$/, "Місце $1: перевірте гравця, роль і фоли.");
}
