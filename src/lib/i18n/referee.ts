export function refereeText(locale: Locale, text: string) {
  if (locale !== "uk") return text;
  if (Object.hasOwn(ukrainian, text)) return ukrainian[text];
  return text
    .replace(/^(N\d+): проверки наблюдались не полностью\.$/, "$1: перевірки спостерігалися не повністю.")
    .replace(/^(N\d+): результат отстрела не установлен\. Продолжение без достоверного результата недопустимо/, "$1: результат відстрілу не встановлено. Продовження без достовірного результату заборонено")
    .replace(/^Роль места (\d+) уточнена позднее: (.*)\. Ранние неизвестные наблюдения не дополнены задним числом\.$/, "Роль місця $1 уточнено пізніше. Причина: $2. Ранні невідомі спостереження збережено.")
    .replace(/^Наблюдавшийся ответ проверки расходится с ролью:/, "Зафіксована відповідь перевірки не відповідає ролі:")
    .replace(/^Место (\d+): пропуск ближайшей речи\.$/, "Місце $1: найближчу промову пропущено.")
    .replace(/^Место (\d+): (\d+) секунд\.$/, "Місце $1: $2 с.")
    .replace(/^Место (\d+): защита 30 секунд\.$/, "Місце $1: захист 30 с.")
    .replace(/^Техническое предупреждение:/, "Технічне попередження:");
}
